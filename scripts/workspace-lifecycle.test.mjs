import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import test from 'node:test';

const source = dirname(dirname(fileURLToPath(import.meta.url)));
const call = (cwd, command, args, success = true, env = process.env) => {
  const result = spawnSync(command, args, { cwd, encoding: 'utf8', env });
  if (success) assert.equal(result.status, 0, `${command}\n${result.stdout}\n${result.stderr}`);
  return result;
};
test('real JJ workspaces keep edits separate, recover from stale, and reject a changed destruction target', { skip: process.platform !== 'linux' }, () => {
  const folder = mkdtempSync(join(tmpdir(), 'abservice-workspaces-'));
  const root = join(folder, 'repo');
  mkdirSync(join(root, 'scripts'), { recursive: true });
  cpSync(join(source, 'scripts/workspace.mjs'), join(root, 'scripts/workspace.mjs'));
  writeFileSync(join(root, '.gitignore'), '.dev-env/\n');
  const git = (args) => call(root, 'git', ['-C', root, ...args]);
  git(['init', '--initial-branch=main']);
  git(['config', '--local', 'user.name', 'Workspace Fixture']);
  git(['config', '--local', 'user.email', 'fixture@example.test']);
  git(['add', '.']); git(['commit', '-m', 'Fixture base']);
  call(root, 'jj', ['git', 'init', '--colocate']);
  const jj = (cwd, args) => call(cwd, 'jj', ['--repository', cwd, '--config', 'user.name="Workspace Fixture"', '--config', 'user.email="fixture@example.test"', ...args]);
  for (const id of ['alpha', 'beta']) call(root, 'node', ['scripts/workspace.mjs', 'create', id, 'main']);
  const a = `${root}-alpha`; const b = `${root}-beta`;
  writeFileSync(join(a, 'alpha.txt'), 'alpha\n');
  writeFileSync(join(b, 'beta.txt'), 'beta\n');
  jj(a, ['describe', '-m', 'alpha']); jj(b, ['describe', '-m', 'beta']);
  assert.equal(existsSync(join(b, 'alpha.txt')), false);
  assert.equal(existsSync(join(a, 'beta.txt')), false);
  const aHead = jj(a, ['log', '--no-graph', '-r', '@', '-T', 'commit_id']).stdout;
  assert.notEqual(aHead, jj(b, ['log', '--no-graph', '-r', '@', '-T', 'commit_id']).stdout);
  const aChange = jj(a, ['log', '--no-graph', '-r', '@', '-T', 'change_id']).stdout.trim();
  jj(b, ['metaedit', '-r', aChange, '-m', 'alpha metadata from shared history']);
  jj(a, ['workspace', 'update-stale']);
  assert.equal(readFileSync(join(a, 'alpha.txt'), 'utf8'), 'alpha\n');
  assert.equal(readFileSync(join(b, 'beta.txt'), 'utf8'), 'beta\n');
  const statePath = join(a, '.dev-env/state.json');
  const state = JSON.parse(readFileSync(statePath, 'utf8'));
  assert.notEqual(state.project, JSON.parse(readFileSync(join(b, '.dev-env/state.json'), 'utf8')).project);
  state.project = 'not-owned-by-this-workspace';
  writeFileSync(statePath, JSON.stringify(state));
  const fake = join(folder, 'bin'); mkdirSync(fake);
  const marker = join(folder, 'docker-called');
  writeFileSync(join(fake, 'docker'), `#!/bin/sh\ntouch '${marker}'\nexit 99\n`, { mode: 0o755 });
  const rejected = call(a, 'node', ['scripts/workspace.mjs', 'destroy', 'alpha'], false, { ...process.env, PATH: `${fake}:${process.env.PATH}` });
  assert.notEqual(rejected.status, 0);
  assert.match(rejected.stderr, /identity does not match/);
  assert.equal(existsSync(marker), false);
});

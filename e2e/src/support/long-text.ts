/**
 * 長い文言の組み立て。
 *
 * <p>
 * 一覧の列幅は中身の長さで変わる。短い文言だけで確かめても、**長いときに崩れないことは言えない**
 * （#359）。確かめる長さは「起こりうる上限」＝列の長さに揃え、半端な長さは使わない。
 * </p>
 */

/**
 * 埋め草。
 *
 * 和文にするのは、折り返しの効き方が欧文と違うため（和文は語の切れ目を持たず、文字の間で折り返す）。
 * 一覧に並ぶのは作品名と記事名なので、確かめる文言も和文でなければ意味が無い。
 */
const FILLER = '長い文言が一覧の幅をどう変えるかを確かめるための文字列。';

/**
 * 先頭を保ったまま、指定の長さちょうどの文言を作る。
 *
 * @param lead
 *            先頭に置く文言（何のための行かを読めるようにするため、必ず残す）
 * @param length
 *            作る文言の長さ。`lead` より短くはできない
 */
export const longTextOf = (lead: string, length: number): string =>
  `${lead}${FILLER.repeat(Math.ceil(Math.max(length - lead.length, 0) / FILLER.length))}`.slice(
    0,
    length,
  );

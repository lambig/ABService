package com.abservice.application.exception;

/**
 * ユースケースが持つ「正常な失敗」の種類
 *
 * <p>
 * 失敗の語彙をアプリケーション層のものとして持ち、HTTP の状態コードを含めない。どの失敗をどの状態コードで返すかは 例外マッパーが決め、API
 * 定義への反映は {@code presentation.rest.openapi} のフィルタが行う。ここに HTTP を
 * 混ぜると、ユースケースが配信の都合を知ることになる。
 * </p>
 *
 * <p>
 * 想定外の失敗（実装の誤り・基盤の障害）はここに含めない。それはどのユースケースでも起こり得るもので、能力として 宣言する意味がない。
 * </p>
 */
public enum Failure {

    /**
     * 入力の値が検証規則を満たさない。
     *
     * <p>
     * 要求本体・問合せ文字列の値だけでなく、経路に現れる識別子の形もここに含まれる（識別子を値オブジェクトへ通す
     * ユースケースは、形が不正な識別子をこの失敗として返す）。
     * </p>
     */
    VALIDATION,

    /**
     * 操作の対象が存在しない。
     *
     * <p>
     * 対象が無いことを失敗とするユースケースだけが持つ。存在しないことを成功として扱うもの（べき等な削除、upsert）は 持たない。
     * </p>
     */
    NOT_FOUND,

    /**
     * 業務ルールに反する、または他の操作と競合した。
     *
     * <p>
     * 業務ルールの違反と、書き込みの競合（編集開始時点の世代の不一致・版列による同時更新の検出）をまとめて表す。
     * 呼び出し側の対処は「読み直して再試行」で同じであり、区別しても扱いが変わらない。
     * </p>
     */
    CONFLICT
}

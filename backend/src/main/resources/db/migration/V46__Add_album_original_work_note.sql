-- 作品に原作の出典の記述を持たせる（#365）
-- アレンジ集の「「○○」より各曲」のように、何をアレンジしたかを人が書いた一文として持つ。
--
-- 構造化しない。作品名だけを構造として持ち、表示側で「より各曲」と組み立てる形は採らない——
-- 「各曲」は作者の主張であって、別の盤が「メインテーマのみ」なら同じ組み立ては嘘になる。
-- DECISIONS 6 が既に「アレンジの原曲はテキスト情報として持つ（原曲そのものをレコードにしない）」
-- としており、本列はその置き場を v1.0 の経路へ広げるもの。
--
-- トラック側には置き場を作らない。トラックと原曲を一対一に特定しない意図がある盤があり、置き場が
-- あると空欄が「未入力」に見えて埋める圧力になる。埋まった瞬間、作者が述べていない対応を
-- システムが主張したことになる（#89 の「人の記述」と「システムの記述」を混ぜない趣旨）。

ALTER TABLE album ADD COLUMN original_work_note VARCHAR(255);

COMMENT ON COLUMN album.original_work_note IS '原作の出典の記述（人が書いた一文。「「○○」より各曲」など）';

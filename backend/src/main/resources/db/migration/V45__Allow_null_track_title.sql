-- トラックのタイトルを省略できるようにする（#360）
-- タイトルを持たないトラックの名は、そのトラックが持つチューン名を繋いだものが正になる。
-- 名を導出して本列へ埋める形は採らない。埋めるとチューンを編集したときタイトルが古いまま残り、
-- 「チューン名を繋いだものが正」が成り立たなくなる。名を答えるのはドメインの値オブジェクト（TrackName）。
--
-- したがって「タイトルも、名を持つチューンも無いトラック」は存在できない。この不変条件はドメインが持つ。
-- 列の制約にしないのは、判定に子テーブル（track_tune）の中身が要るため——DB の制約で表すと、
-- チューン側の変更のたびに親を見に行く形になり、不変条件の所在が2箇所に割れる。

ALTER TABLE track ALTER COLUMN title DROP NOT NULL;

COMMENT ON COLUMN track.title IS 'トラックのタイトル（セット全体の名前でもよい）。NULLの場合はチューン名を繋いだものが名になる';
